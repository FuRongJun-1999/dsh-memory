import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import vm from 'node:vm';
const read = name => readFileSync(new URL(name, import.meta.url),'utf8');
const client = read('./web/client.js');
const output = `/* generated by build-ui.mjs */\nwindow.__ModuleLoader__.load({id:"@furongjun1999/dsh-memory",factory:function(require){var module={exports:{}};\n${client}\nreturn module.exports;}});\n`;
new vm.Script(read('./web/app.js'),{filename:'web/app.js'});
new vm.Script(read('./web/entry.js'),{filename:'web/entry.js'});
let registration; new vm.Script(output).runInNewContext({window:{__ModuleLoader__:{load:r=>registration=r}}});
const plugin=registration.factory(name=> {if(name==='react')return {createElement(){}};throw new Error('Unexpected module '+name);});
if(typeof plugin.apply!=='function'||!plugin.inject.includes('slots'))throw new Error('Client bundle exports invalid');
const slots=[];plugin.apply({slots:{inject:(name,fn)=>fn(),register:(meta,component)=>{slots.push(meta);return()=>{};}}});
if(slots.map(s=>s.name).join(',')!=='main,sidebar.panellist')throw new Error('Expected sidebar and main slots');
mkdirSync(new URL('./lib/lib/',import.meta.url),{recursive:true});
copyFileSync(new URL('./src/lib/console_web.mjs',import.meta.url),new URL('./lib/lib/console_web.mjs',import.meta.url));
writeFileSync(new URL('./lib/client.js',import.meta.url),output,'utf8');
console.log('UI build passed: syntax, factory exports, sidebar/main registration; host module copied.');
