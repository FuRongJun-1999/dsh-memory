import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import vm from 'node:vm';
const read = name => readFileSync(new URL(name, import.meta.url),'utf8');
// issue #791：面板改为 srcdoc 内嵌同一份 UI，页面 fetch 经 postMessage 由主 frame 代发。
// 复核 0077/0093 指出的关键点：内联脚本**没有 defer 语义**，故桥脚本留在 <head>，
// 而 app.js 必须内联到 </body> 之前（DOM 已就绪，与 defer 等价），否则 app.js 在 head 阶段跑必崩。
const ESC = s => s.replace(/<\/(script|style)/gi, '<\\/$1');
const SHIM = `(function(){
// issue #791：srcdoc 文档里 history.replaceState(s,t,'#x') 会抛
// 「URL 'http://…/#x' cannot be created in a document with origin … and URL 'about:srcdoc'」
// ⇒ 启动序列被打断、面板卡在「连接中」。这里把 URL 参数降级（只写 state），
// 面板内部导航不依赖真实 hash（hashchange 在 srcdoc 里也不会触发）。
var R=history.replaceState.bind(history),PU=history.pushState.bind(history);
history.replaceState=function(s,t,u){try{R(s,t,u)}catch(e){try{R(s,t)}catch(e2){}}};
history.pushState=function(s,t,u){try{PU(s,t,u)}catch(e){try{PU(s,t)}catch(e2){}}};
var P=window.parent,seq=0,waits={};
window.addEventListener('message',function(e){var d=e.data||{};
if(d.__lingshu!=='res')return;var w=waits[d.id];if(!w)return;delete waits[d.id];w(d);});
window.fetch=function(u,o){o=o||{};var id=++seq;return new Promise(function(res,rej){
waits[id]=function(d){if(d.error){rej(new Error(d.error));return}
res({ok:d.ok,status:d.status,text:function(){return Promise.resolve(d.text)}});};
try{P.postMessage({__lingshu:'req',id:id,url:String(u),method:o.method||'GET',
body:(o.body==null?null:o.body),headers:o.headers||{}},'*');}catch(err){rej(err);}});};})();`;
const css = ESC(read('./web/style.css'));
const appJs = ESC(read('./web/app.js'));
const LINK = '<link rel="stylesheet" href="/plugins/lingshu/style.css">';
const SCRIPT = '<script defer src="/plugins/lingshu/app.js"></script>';
const html = read('./web/index.html');
if (!html.includes(LINK) || !html.includes(SCRIPT)) throw new Error('index.html 结构已变：找不到待内联的 link/script 原串');
const panelHtml = html
  .replace(LINK, () => '<style>' + css + '</style>')
  .replace(SCRIPT, () => '<script>' + SHIM + '</script>')
  .replace('</body>', () => '<script>' + appJs + '</script></body>');
// 只查**静态引用**是否消失（app.js 里的 /plugins/lingshu/call|meta 是运行时 fetch，经桥转发，属正常）
if (panelHtml.includes(LINK) || panelHtml.includes(SCRIPT)) throw new Error('srcdoc 内联失败：仍残留 link/script 静态外链');
if (/<link[^>]+href=/i.test(panelHtml)) throw new Error('srcdoc 内联失败：仍有 <link href>');
if ((panelHtml.match(/<script>/g) || []).length !== 2) throw new Error('srcdoc 内联失败：<script> 数量不为 2');
const iShim = panelHtml.indexOf('__lingshu'), iApp = panelHtml.indexOf(appJs.slice(0, 60));
if (iShim < 0 || iApp < 0 || !(iShim < iApp)) throw new Error('srcdoc 顺序错误：桥脚本必须在 app.js 之前');
if (panelHtml.indexOf(appJs.slice(0, 60)) < panelHtml.lastIndexOf('</body>') - appJs.length - 40) throw new Error('app.js 未内联到 </body> 之前（defer 语义丢失）');
if (/<\/script/i.test(read('./web/app.js'))) throw new Error('app.js 含 </script 字面量（需先转义）');
const client = read('./web/client.js').replace(/__PANEL_HTML__/g, () => JSON.stringify(panelHtml));
if (!client.includes('srcDoc')) throw new Error('client.js 未接收到内联面板（__PANEL_HTML__ 未替换）');
const output = `/* generated by build-ui.mjs */\nwindow.__ModuleLoader__.load({id:"@furongjun1999/dsh-memory",factory:function(require){var module={exports:{}};\n${client}\nreturn module.exports;}});\n`;
new vm.Script(read('./web/app.js'),{filename:'web/app.js'});
new vm.Script(read('./web/entry.js'),{filename:'web/entry.js'});
let registration; new vm.Script(output).runInNewContext({window:{__ModuleLoader__:{load:r=>registration=r}}});
const plugin=registration.factory(name=> {if(name==='react')return {createElement(){}};throw new Error('Unexpected module '+name);});
if(typeof plugin.apply!=='function'||!plugin.inject.includes('slots'))throw new Error('Client bundle exports invalid');
const slots=[];plugin.apply({slots:{inject:(name,fn)=>fn(),register:(meta,component)=>{slots.push(meta);return()=>{};}}});
if(slots.map(s=>s.name).join(',')!=='main,sidebar.panellist')throw new Error('Expected sidebar and main slots');
mkdirSync(new URL('./lib/lib/',import.meta.url),{recursive:true});
copyFileSync(new URL('./src/lib/console_web.mjs',import.meta.url),new URL('./lib/lib/console_web.mjs',import.meta.url));
writeFileSync(new URL('./lib/client.js',import.meta.url),output,'utf8');
console.log('UI build passed: srcdoc ' + panelHtml.length + ' chars (CSS+SHIM+app inline), sidebar/main registration, host module copied.');