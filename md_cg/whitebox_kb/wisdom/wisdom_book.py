    def dex_auto_test(self, a_ref, b_ref, archive=True):
        """AI vs AI：学科招式 + 通用条件操作五式交替施压，四类结果判定，报告归档。"""
        A, B = self._resolve_entry(a_ref), self._resolve_entry(b_ref)
        if not A or not B:
            return {"error": "entry_not_found", "a": a_ref, "b": b_ref}
        na, nb = A.state_attributes.get("name"), B.state_attributes.get("name")
        rounds = []
        offsets = {}
        stable = {}
        for attacker, defender, label in ((A, B, f"{na}→{nb}"), (B, A, f"{nb}→{na}")):
            moves = self._moves(attacker) + self.OPERATION_MOVES
