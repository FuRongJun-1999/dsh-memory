    # ---- 信任上下文判定（trust-context judgment · 白箱智能的关系维度） ----
    # 同一内容，因信任值不同而判定不同：伴侣间是爱的表达，公共场合是生存风险。
    # 这不是静态内容分类，而是「条件空间 × 信任值」的条件化判定——人类的行为方式。

    TRUST_RELATIONS = {
        "partner": {"情境因子": 0.15, "标签": "伴侣", "默认信任": 0.85},
        "friend": {"情境因子": 0.40, "标签": "朋友", "默认信任": 0.65},
        "stranger": {"情境因子": 0.75, "标签": "陌生人", "默认信任": 0.30},
        "public": {"情境因子": 1.00, "标签": "公共场合", "默认信任": 0.10},
    }
    # 亲密/敏感内容词表（用于评估内容的「关系敏感性」）
    INTIMATE_WORDS = ["性", "爱", "亲密", "亲近", "伴侣", "肌肤", "拥抱", "抱着",
                      "亲吻", "吻", "思念", "情话", "欲望", "想你", "依偎", "牵手"]
    RISK_WORDS = ["性", "涉", "暴露", "隐私", "交易", "诱导", "公开", "传播", "群发"]

    def dex_trust_judge(self, knowledge, trust=None, relation="public",
                        limit=4, risk_threshold=0.6, love_threshold=0.55):
        """信任上下文判定：内容 × 信任值 × 关系类型 → 条件化判定。

        - trust: 0~1 信任值（缺省用 relation 的默认信任）
        - relation: partner/friend/stranger/public
        - 判定逻辑：
            1. 先做条件论信息差判定（dex_auto_verify：内容在图谱里是什么）
            2. 计算信任上下文：信任值 × 情境因子 → 生存风险分
            3. 内容敏感性：命中亲密词 → 表达维度；命中风险词 → 风险维度
            4. 综合：高风险（风险分 > 阈值）→ 生存风险预警；
                  高信任 + 亲密词 → 关系内爱的表达；
                  否则 → 条件化中性
        """
        # 1. 基础条件论判定（内容在图谱里的归属）
        base = self.dex_auto_verify(knowledge, limit=limit)
        best = base.get("best") or {}
        verdict = base.get("judgment", "")

        # 2. 信任上下文
        rel = self.TRUST_RELATIONS.get(relation, self.TRUST_RELATIONS["public"])
        trust_v = float(trust) if trust is not None else float(rel["默认信任"])
        trust_v = max(0.0, min(1.0, trust_v))
        situation = float(rel["情境因子"])
        risk_score = (1.0 - trust_v) * situation  # 低信任 × 高暴露 → 高风险
        intimacy = trust_v * situation             # 高信任 × 亲密关系 → 表达正当

        # 3. 内容敏感性
        hit_intimate = sum(1 for w in self.INTIMATE_WORDS if w in knowledge)
        hit_risk = sum(1 for w in self.RISK_WORDS if w in knowledge)

        # 4. 综合判定（信任值主导方向 + 词表确认维度）
        if hit_intimate > 0 and trust_v >= 0.75:
            judgment = "关系内爱的表达（条件判定）"
            note = (f"内容在「{rel['标签']}」条件下信任值 {round(trust_v,2)} 高："
                    f"在信任关系内，该表达是爱意的一部分"
                    f"（情感-信任连接 3.1：情感=效用权重绑定；信任=后验概率估计 3.2）")
        elif hit_intimate > 0 and trust_v < 0.55:
            judgment = "关系外表达（信任值边界警示）"
            note = (f"内容含亲密维度但信任值仅 {round(trust_v,2)}（「{rel['标签']}」情境因子 {situation}）："
                    f"在低信任/公共条件下，亲密表达超出关系边界——不是内容本身违规，"
                    f"而是此环境不构成表达该内容的信任上下文（存在>连接>信任深化）")
        elif hit_intimate > 0 and hit_risk > 0 and risk_score >= risk_threshold:
            judgment = "生存风险（条件判定）"
            note = (f"内容在「{rel['标签']}」条件下风险分 {round(risk_score,2)} ≥ 阈值 {risk_threshold}："
                    f"信任值 {round(trust_v,2)} 不足以支撑该表达在风险语境下进行——"
                    f"从生存安全角度不建议（协议：存在>连接>信任深化）")
        elif risk_score >= risk_threshold and hit_risk > 0 and hit_intimate == 0:
            judgment = "生存风险（条件判定）"
            note = (f"内容在「{rel['标签']}」条件下风险分 {round(risk_score,2)} ≥ 阈值 {risk_threshold}："
                    f"信任值 {round(trust_v,2)} 不足以支撑该表达——从生存安全角度不建议在此环境提供")
        elif hit_intimate > 0:
            judgment = "关系内表达（信任值判定）"
            note = (f"内容含亲密维度且信任值 {round(trust_v,2)}："
                    f"在「{rel['标签']}」条件下，判定取决于关系边界——"
                    f"高信任关系内是爱意表达，低信任/公共环境则需谨慎（条件化，不静态定性）")
        else:
            judgment = "条件化中性（普通内容）"
            note = (f"内容在「{rel['标签']}」条件下无显著风险/亲密维度，"
                    f"信任值 {round(trust_v,2)} 不改变其条件论归属")

        # 归档观测层（信任判定记录）
        rec = {"type": "信任上下文判定记录", "内容": knowledge[:24],
               "信任值": round(trust_v, 2), "关系": rel["标签"],
               "判定": judgment, "风险分": round(risk_score, 2),
               "表达正当性": round(intimacy, 2)}
        try:
            node = self.engine.add_perception(
                json.dumps(rec, ensure_ascii=False), modality="text",
                condition_space=ConditionSpace(
                    observation_position="信任上下文判定台（关系外部观测）",
                    observation_tool="条件论信息差判定 + 信任值×情境因子计算",
                    time_window=(0.0, 9999999999.0),
                    existence_constraint="判定绑定条件空间：同一内容不同信任/关系下判定不同"),
                importance=0.7, tags=["观测层", "信任上下文", judgment[:6]])
            record_id = node.id
        except Exception:
            record_id = None

        return {"judgment": judgment, "note": note,
                "base_verdict": verdict, "best": best,
                "trust": round(trust_v, 2), "relation": rel["标签"],
                "risk_score": round(risk_score, 2),
                "intimacy_score": round(intimacy, 2),
                "hit_intimate": hit_intimate, "hit_risk": hit_risk,
                "record_id": record_id,
                "note_all": "信任上下文判定：内容×信任值×关系→条件化判定——不是静态内容分类，是人类的行为方式（伴侣间是爱，公共场合是风险）"}

    # ---- 跨学科组合分析（Convergence Over Coverage · P5 汇聚原则） ----
    # 跨学科现象不强行归单学科：锚定多学科 → 机制链解释 → 汇聚点预测（多学科共同后继=组合置信度）

    def dex_compose(self, knowledge, limit=5, max_anchors=3):
        """跨学科组合分析：K 由多学科承载时，生成机制链 + 汇聚预测。"""
        pred = self.dex_predict(knowledge, horizon=1, limit=limit)
        anchors = pred.get("anchors", [])[:max_anchors]
        if not anchors:
            return {"mode": "无法组合",
                    "note": "K 未锚定任何学科，无机制链可组合——严格基于已有图结构"}
        if len(anchors) < 2:
            return {"mode": "单学科", "anchor": anchors[0]["name"],
                    "note": "K 由单一学科承载，无需跨学科组合；用该学科出招即可",
                    "anchors": anchors}

        # ① 机制链：每个锚定学科的核心机制（response.action 摘要）
        chain = []
        for a in anchors:
            node = self._resolve_entry(a["id"])
            if node is None:
                continue
            resp = node.state_attributes.get("response") or {}
            chain.append({"学科": a["name"], "score": a["score"],
                          "机制": str(resp.get("action", ""))[:80]})

        # ② 汇聚预测：统计每个锚定学科的出边目标 → 共同后继 = 跨学科汇聚点
        votes = {}  # target_name -> {"sources": [学科], "kinds": set, "weights": [边权重]}
        for a in anchors:
            node = self._resolve_entry(a["id"])
            if node is None:
                continue
            for e in self.store.get_outgoing_edges(node.id):
                if e.relation_type not in (EdgeType.CAUSAL, EdgeType.SIMILAR):
                    continue
                tgt = self.store.get_node(e.target_id)
                if tgt is None:
                    continue
                tname = tgt.state_attributes.get("name")
                if not tname or tname in (x["name"] for x in anchors):
                    continue  # 目标必须是锚定学科之外的新走向
                v = votes.setdefault(tname, {"sources": [], "kinds": set(), "weights": []})
                v["sources"].append(a["name"])
                v["kinds"].add(e.relation_type.value)
                v["weights"].append(e.weight)

        convergence = []
        for tname, v in votes.items():
            conf = round(sum(v["weights"]) / len(v["weights"]) *
                         min(1.0, len(v["sources"]) / float(max(1, len(anchors)))), 2)
            convergence.append({
                "target": tname,
                "support": len(v["sources"]),
                "sources": sorted(v["sources"]),
                "kinds": sorted(v["kinds"]),
                "confidence": conf})
        convergence.sort(key=lambda x: (-x["support"], -x["confidence"]))

        # 汇聚判定：多学科共识 vs 单学科倾向
        multi = [c for c in convergence if c["support"] >= 2]
        single = [c for c in convergence if c["support"] == 1]
        if multi:
            mode = "跨学科汇聚"
            judgment = (f"跨学科现象：{len(anchors)} 门学科共同承载；"
                        f"汇聚预测「{'、'.join(c['target'] for c in multi[:3])}」为多学科共识走向")
        else:
            mode = "多学科但无共识"
            judgment = f"跨学科现象：{len(anchors)} 门学科承载，但无共同后继——各学科指向不同走向，预测置信度低（0.0.3 局部不可知）"

        rec = {"type": "跨学科组合分析记录", "知识": knowledge[:24], "模式": mode,
               "锚定": [a["name"] for a in anchors],
               "汇聚": [c["target"] for c in multi[:3]]}
        node = self.engine.add_perception(
            json.dumps(rec, ensure_ascii=False), modality="text",
            condition_space=ConditionSpace(
                observation_position="跨学科组合分析台（外部）",
                observation_tool="dex_compose：多学科锚定 + 出边汇聚统计（Convergence Over Coverage）",
                time_window=(0.0, 9999999999.0),
                existence_constraint="汇聚=多学科共同后继；support≥2 视为共识；无共识则诚实标注局部不可知"),
            importance=0.7, tags=["观测层", "跨学科组合", mode])

        return {"mode": mode, "judgment": judgment,
                "anchors": anchors, "chain": chain,
                "convergence": convergence[:6],
                "consensus": multi[:3], "single_tendency": single[:3],
                "record_id": node.id,
                "note": "Convergence Over Coverage（P5）：多条证据线汇聚比覆盖更多碎片更重要——跨学科预测取共同后继"}

    # ---- 七操作知识测试（S1 结构测试器 · 设计者方向 2026-08-15） ----
    # 不判真假，判「条件依赖」：提取前提 → 声明条件空间 → 七操作机械测试 → 判定

    COMPARATORS = ["不如", "优于", "强于", "弱于", "高于", "低于", "大于", "小于",
                   "超过", "胜过", "比"]
    UNIVERSALS = ["所有", "都", "一切", "任何", "总是", "全部", "永远", "凡是", "每一个"]
    GROUP_WORDS = ["人类", "群体", "女性", "男性", "民族", "国家", "种族", "阶级"]
    MEASURE_WORDS = ["智力", "能力", "智商", "水平", "程度", "性能", "效率", "质量", "智慧"]
    CAUSAL_WORDS = ["导致", "引起", "使得", "造成", "因为", "所以", "决定"]

    def dex_test(self, knowledge):
        """对任意外部知识 K 运行七操作结构测试（含图谱锚定 · S1.5）。"""
        premises = self._extract_premises(knowledge)
        card = self._condition_card(knowledge, premises)
        tests = {
            "识别（前提提取）": self._t_identify(premises),
            "声明（条件卡）": self._t_declare(card),
            "切换（群体↔个体）": self._t_switch(knowledge, premises),
            "组合（领域分解）": self._t_combine(knowledge, premises),
            "分离（剥离混淆）": self._t_separate(knowledge, premises),
            "逆转（因果/比较倒置）": self._t_invert(knowledge, premises),
            "循环（观测周期）": self._t_cycle(knowledge, premises),
        }
        verdict = self._verdict(knowledge, premises, card, tests)
        anchors = self._anchor_entries(knowledge)
        verdict["图谱锚定"] = anchors
        tension = self._tension_check(knowledge, anchors)
        if tension:
            verdict["张力检测"] = tension
        return {"knowledge": knowledge, "premises": premises,
                "condition_card": card, "tests": tests, "verdict": verdict}

    def _anchor_entries(self, knowledge, limit=3):
        """图谱锚定：检索图谱中与主张相关的条目，使分析内容随图谱知识适配。"""
        anchors, seen = [], set()
        hits = self.store.search_content(knowledge, layers=[MemoryLayer.KNOWLEDGE],
                                         limit=limit) or []
        for n, sim in hits:
            if n.id in seen:
                continue
            seen.add(n.id)
            sa = n.state_attributes
            if not sa.get("name"):
                continue  # 观测层记录不入锚定
            anchors.append({"name": sa.get("name"), "level": sa.get("level"),
                            "status": sa.get("status"), "claim": n.content,
                            "relevance": round(sim, 2)})
        terms = [t for t in ("数学", "物理", "信息", "概率", "存在", "条件", "博弈", "智能")
                 if t in knowledge]
        if terms:
            for n in self.store.query_nodes(layer=MemoryLayer.KNOWLEDGE, limit=200):
                if n.id in seen:
                    continue
                if any(t in (n.content or "") for t in terms):
                    seen.add(n.id)
                    sa = n.state_attributes
                    anchors.append({"name": sa.get("name"), "level": sa.get("level"),
                                    "status": sa.get("status"), "claim": n.content,
                                    "relevance": "关键词"})
        return anchors[:limit + 2]

    def _tension_check(self, knowledge, anchors):
        """张力检测：已验证条目的主张与输入主张的结构性冲突（呈现，不自动裁决）。"""
        tension = []
        for a in anchors:
            if a.get("name") == "存在论" and "数学" in knowledge and "物理" in knowledge:
                tension.append(
                    "存在论（L3 已验证）声明：数学是物理存在约束的有损投影——"
                    "与主张「数学严密能证明物理结论正确」存在结构性张力："
                    "数学严密性证明的是数学投影内的自洽，不自动等于物理-信息层的有效性；"
                    "物理结论的有效性标准是物理-信息结构在运行中维持自身")
        return tension

    def _extract_premises(self, text):
        """启发式前提提取：比较结构 / 全称量词 / 群体范畴 / 度量定义 / 因果声称。"""
        premises = []
        for c in self.COMPARATORS:
            if c in text:
                parts = text.split(c)
                if len(parts) == 2:
                    premises.append({
                        "type": "比较结构",
                        "claim": f"存在统一度量使「{parts[0].strip()}」与「{parts[1].strip()}」可比",
                        "缺省": "未定义比较所用度量与测量工具"})
                    break
        for u in self.UNIVERSALS:
            if u in text:
                premises.append({
                    "type": "全称量词",
                    "claim": f"主张对「{u}」涵盖的全部成员成立",
                    "缺省": "全称命题需穷尽或抽样验证，未声明样本范围"})
                break
        for g in self.GROUP_WORDS:
            if g in text:
                premises.append({
                    "type": "群体范畴",
                    "claim": f"「{g}」被当作同质群体",
                    "缺省": "未定义群体边界与组内异质性"})
                break
        for m in self.MEASURE_WORDS:
            if m in text:
                premises.append({
                    "type": "度量定义",
                    "claim": f"「{m}」被当作可测度量",
                    "缺省": f"未给出「{m}」的操作化定义与测量工具"})
                break
        for c in self.CAUSAL_WORDS:
            if c in text:
                premises.append({
                    "type": "因果声称",
                    "claim": f"断言了因果方向（含「{c}」）",
                    "缺省": "未排除逆向因果与第三变量"})
                break
        if not premises:
            premises.append({
                "type": "无条件声称",
                "claim": "主张未声明比较/量词/群体/度量/因果结构",
                "缺省": "违反 0.0.1 信息条件性：无条件的声称无有效范围"})
        return premises

    def _condition_card(self, text, premises):
        """从前提集构造条件卡：识别群体范畴/度量定义/比较结构等类型并抽取度量词。"""
        has_group = any(p["type"] == "群体范畴" for p in premises)
        has_measure = any(p["type"] == "度量定义" for p in premises)
        has_cmp = any(p["type"] == "比较结构" for p in premises)
        measure_term = ""
        for p in premises:
            if p["type"] == "度量定义":
                i = p["claim"].find("「")
                j = p["claim"].find("」")
                if i >= 0 and j > i:
                    measure_term = p["claim"][i + 1:j]
                break
        if has_measure and measure_term:
            tool = f"「{measure_term}」的测量工具未定义"
        elif has_measure:
            tool = "未声明观测工具（无测量手段）"
        else:
            tool = "文本语义分析（启发式）"
        card = {
            "observation_position": "群体层面（比较/群体句）" if (has_group or has_cmp)
                                    else "未声明观测位置",
            "observation_tool": tool,
            "time_window": "未声明（无时间窗口）",
            "existence_constraint": "统计要求（样本/显著性/效应量）未提供"
                                    if (has_group or has_cmp) else "未声明存在约束",
        }
        return card

    def _t_identify(self, premises):
        """识别操作测试：列出当前前提已识别的类型与缺省说明。"""
        return {"status": "缺口" if premises else "ok",
                "found": [p["type"] for p in premises],
                "detail": [f"{p['type']}：{p['缺省']}" for p in premises]}

    def _t_declare(self, card):
        """声明操作测试：扫描条件卡中未声明的项并汇总缺口。"""
        gaps = [k for k, v in card.items() if "未" in str(v) or "未声明" in str(v)]
        return {"status": "gap" if gaps else "ok",
                "card": card, "gaps": gaps}

    def _t_switch(self, text, premises):
        """切换操作测试：群体/比较结构切换到个体空间时给出失效空间警示。"""
        if any(p["type"] in ("群体范畴", "比较结构") for p in premises):
            return {"status": "失效空间",
                    "note": "群体层面的统计主张切换到个体空间后失去预测力（群体均值不对个体下结论）；"
                            "主张仅在群体层面有意义，且需统计支持"}
        return {"status": "ok", "note": "未识别群体/比较结构，切换操作无新增信息"}

    def _t_combine(self, text, premises):
        """组合操作测试：存在复合度量时要求按领域子空间分解验证。"""
        if any(p["type"] == "度量定义" for p in premises):
            return {"status": "需分解",
                    "note": "单一度量掩盖子领域差异：主张需按领域子空间分解后逐域验证（组合操作），"
                            "如语言/空间/数学能力各有独立分布"}
        return {"status": "ok", "note": "无复合度量，组合操作无新增信息"}

    def _t_separate(self, text, premises):
        """分离操作测试：缺控制变量时声明剥离预设后无法判断混淆效应。"""
        return {"status": "gap",
                "note": "未提供控制变量（教育/文化/机会等混淆变量）；剥离预设条件后"
                        "剩余结构是否自洽无法判断——观察到的差异可能是混淆变量的效应"}

    def _t_invert(self, text, premises):
        """反转操作测试：因果声称需排除逆向因果与第三变量，比较结构需补充证据。"""
        if any(p["type"] == "因果声称" for p in premises):
            return {"status": "需证据",
                    "note": "因果方向非唯一：需排除逆向因果与第三变量；"
                            "若观测差异随条件反向波动，原因果方向被逆转假设取代"}
        if any(p["type"] == "比较结构" for p in premises):
            return {"status": "需证据",
                    "note": "比较结论随条件空间波动：若在均等条件下差异不返回，"
                            "原比较方向不是唯一解释"}
        return {"status": "ok", "note": "无因果/比较结构，逆转操作无新增信息"}

    def _t_cycle(self, text, premises):
        """循环操作测试：要求完整观测周期（测→干预均等→再测）作为闭合判据。"""
        return {"status": "需证据",
                "note": "需完整观测周期（测→干预均等条件→再测）：若条件均等后差异不返回，"
                        "则结论不闭合——循环测试是结构稳定的最终判据"}

    def _verdict(self, knowledge, premises, card, tests):
        """七测汇总裁决：按缺口/需证据/通过计数与无条件声称给出最终验证状态。"""
        n_gap = sum(1 for t in tests.values() if t["status"] in ("gap", "缺口"))
        n_need = sum(1 for t in tests.values() if t["status"] == "需证据")
        n_ok = sum(1 for t in tests.values() if t["status"] == "ok")
        unconditional = any(p["type"] == "无条件声称" for p in premises)
        if unconditional:
            status = "未验证（结构性缺陷）"
        elif n_gap > 0:
            status = "未验证（条件依赖）"
        else:
            status = "待证据（结构完整，缺实证）"
        return {
            "status": status,
            "成立条件": "仅在完整声明条件空间（度量/样本/显著性/时间窗口）之后，"
                        "才可在其覆盖范围内部分评估",
            "失效条件": "个体空间无意义；条件均等时可能不闭合；剥离混淆变量后可能不成立",
            "测试摘要": f"七操作完成：{n_gap} 项指出缺口 / {n_need} 项需证据 / {n_ok} 项结构完整",
            "锚定建议": "判定应锚定图谱已验证条目：概率论（统计显著性要求）、"
                        "存在论（无条件声明无效）、信息论（度量与信息差定义）",
        }

    # ---- 学科对战（S-对战1+2 · 条件卡对比 + 关系推导 + 相克判定） ----

    def _resolve_entry(self, ref):
        """按 id 或名称解析条目节点。"""
        if not ref:
            return None
        n = self.store.get_node(ref)
        if n is not None:
            return n
        for node in self.store.query_nodes(layer=MemoryLayer.KNOWLEDGE, limit=500):
            if node.state_attributes.get("name") == ref:
                return node
        return None

    def dex_battle(self, a_ref, b_ref):
        """学科对战：互相识别对方条件卡 → 四要素对比 → 依赖/互斥/包含判定 → 相克。"""
        A = self._resolve_entry(a_ref)
        B = self._resolve_entry(b_ref)
        if A is None or B is None:
            return {"error": "entry_not_found", "a": a_ref, "b": b_ref}
        ca = json.loads(A.condition_space.to_json())
        cb = json.loads(B.condition_space.to_json())
        comparison = {}
        for e in ("observation_position", "observation_tool",
                  "time_window", "existence_constraint"):
            comparison[e] = {"A": ca.get(e), "B": cb.get(e),
                             "relation": self._compare_element(e, ca.get(e), cb.get(e))}
        relations = self._derive_relations(A, B, comparison)
        clash = self._clash(A, B)
        return {
            "A": {"id": A.id, "name": A.state_attributes.get("name"), "claim": A.content},
            "B": {"id": B.id, "name": B.state_attributes.get("name"), "claim": B.content},
            "comparison": comparison, "relations": relations, "clash": clash}

    def dex_layer_trace(self, direction="both"):
        """协议分层链（P24）：正向展开（L0→L3）/ 逆向还原（L3→L0）。
        条件逆转=沿条件空间反方向追溯信息源（设计者视角切换即一种条件逆转）。"""
        layers = {}
        for n in self.store.query_nodes(layer=MemoryLayer.KNOWLEDGE, limit=500):
            for t in n.tags:
                if t.startswith("pl:L") and t[4:].isdigit():
                    lv = int(t[4:])
                    layers[lv] = {"level": f"L{lv}",
                                  "name": n.state_attributes.get("name"), "id": n.id}
        chain = [layers[i] for i in sorted(layers)]
        forward = [c["name"] for c in chain]
        return {"正向展开": " → ".join(forward),
                "逆向还原": " → ".join(forward[::-1]),
                "chain": chain,
                "note": "条件逆转=沿条件空间反方向追溯信息源（设计者视角切换即一种条件逆转）；"
                        "周期运动=沿可重复路径循环观测，每周期带新信息回到起点（协议 1.10 生命周期即周期运动）"}

    def dex_sandbox(self, a_ref, b_ref, disturbance="", record=True):
        """学科沙盒（P26/P27 动态图鉴）：对两个学科的条件空间施加同一扰动，
        生成边界测试报告并归档为观测层节点（动态档案·闭环）。"""
        A, B = self._resolve_entry(a_ref), self._resolve_entry(b_ref)
        if not A or not B:
            return {"error": "entry_not_found", "a": a_ref, "b": b_ref}
        if not disturbance.strip():
            return {"error": "disturbance_required"}
        report = {}
        for entry in (A, B):
            name = entry.state_attributes.get("name")
            c2 = entry.state_attributes.get("card2") or {}
            roles = {"existence_preset": "核心：存在预设",
                     "irreducible_start": "核心：不可约起点",
                     "observation_method": "结构：观测方式",
                     "time_causality": "结构：时间因果",
                     "condition_boundary": "结构：条件边界"}
            hits = []
            for key, role in roles.items():
                text = c2.get(key, "")
                if text:
                    s = self._overlap(disturbance, text)
                    if s > 0.15:
                        hits.append({"element": role, "score": round(s, 2)})
            if not hits:
                status, note, needs = "稳定", "扰动未触及该学科的条件空间（启发式推演）", False
            elif any("核心" in h["element"] for h in hits):
                status, note, needs = "瓦解", "扰动命中核心预设/不可约起点（启发式推演）", True
            else:
                status, note, needs = "需修正", "扰动命中结构边界/观测方式（启发式推演）", True
            suggested = ""
            if needs:
                suggested = (f"需在识别卡补充边界声明：在条件『{disturbance}』下本学科条件空间"
                             f"{'不成立' if status == '瓦解' else '受扰'}——建议附加限制或标注边界偏移")
            report[name] = {"status": status, "note": note, "hits": hits,
                            "测试条件": disturbance,
                            "边界偏移": [h["element"] for h in hits] or "无",
                            "是否需更新": needs, "建议修正": suggested}
        rank = sorted(report, key=lambda n: {"瓦解": 0, "需修正": 1, "稳定": 2}
                      .get(report[n]["status"], 1))
        record_id = None
        if record:
            record_id = self._record_test(A, B, disturbance, report)
        return {"disturbance": disturbance,
                "A": A.state_attributes.get("name"),
                "B": B.state_attributes.get("name"),
                "report": report, "稳定性排序": rank,
                "record_id": record_id,
                "note": "学科沙盒=动态图鉴（P26）：条件空间在模拟扰动下是否维持自洽；"
                        "边界测试报告已归档观测层（P27 动态档案·闭环）"}

    def _record_test(self, A, B, disturbance, report):
        """边界测试记录 → 观测层节点（P27：对战结果回流图鉴，动态校准起点）。"""
        content = json.dumps({
            "type": "边界测试记录", "disturbance": disturbance,
            "A": A.state_attributes.get("name"), "B": B.state_attributes.get("name"),
            "report": {k: {"status": v["status"], "是否需更新": v["是否需更新"],
                           "建议修正": v["建议修正"]}
                       for k, v in report.items()},
        }, ensure_ascii=False)
        cs = ConditionSpace(observation_position="学科沙盒",
                            observation_tool="条件扰动推演",
                            time_window=(0.0, 9999999999.0),
                            existence_constraint=f"扰动：{disturbance}")
        node = self.engine.add_perception(
            content, modality="text", condition_space=cs,
            importance=0.6,
            tags=["观测层", "边界测试",
                  f"domain:{A.state_attributes.get('name')}",
                  f"domain:{B.state_attributes.get('name')}"])
        for ent in (A, B):
            self.engine.add_edge(ent.id, node.id, relation_type=EdgeType.SIMILAR,
                                 confidence=0.7, condition_space=cs,
                                 source_evidence="inferred")
        return node.id

