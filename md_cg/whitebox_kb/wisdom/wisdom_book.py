    def seed_history(self):
        """归档历史对战记录（观测层）：BATTLE-2026-001/002（标准报告模板 P31/P33）。"""
        nodes = self.store.query_nodes(layer=MemoryLayer.KNOWLEDGE, limit=500)
        if any("历史对战" in (n.tags or []) for n in nodes):
            return {"status": "already_archived"}
        archived = []
        for rec in self.HISTORY_RECORDS:
            content = json.dumps({"type": "历史对战记录", **rec}, ensure_ascii=False)
            cs = ConditionSpace(observation_position="历史对战后复盘",
                                observation_tool="固定招式顺序推演",
                                time_window=(0.0, 9999999999.0),
                                existence_constraint="报告由设计者对话历史产生（2026-07-30/31）")
            rec_type = rec.get("类型", "历史对战")
            tags = ["观测层", rec_type] + [f"domain:{n}" for n in rec["相关学科"]]
            if rec_type == "历史对战":
                tags.append("边界测试")
            node = self.engine.add_perception(content, modality="text", condition_space=cs,
                                              importance=0.7, tags=tags)
            for name in rec["相关学科"]:
                ent = self._resolve_entry(name)
                if ent:
                    self.engine.add_edge(ent.id, node.id, relation_type=EdgeType.SIMILAR,
                                         confidence=0.8, condition_space=cs,
                                         source_evidence="extracted")
            archived.append({"报告编号": rec["报告编号"], "record_id": node.id})
        return {"status": "archived", "records": archived}

    def dex_homology(self, entry_ref, strip_concepts=None):
        """内部同源性检验（P34）：版本A（完整）vs 版本B（剥离指定概念）对战中
        检验「条件论是装饰还是必要结构」——添加功能还是揭示已有结构。"""
        A = self._resolve_entry(entry_ref)
        if not A:
            return {"error": "entry_not_found", "entry": entry_ref}
        concepts = strip_concepts or ["条件", "条件空间", "视角切换", "识别卡"]
        na = A.state_attributes.get("name")
        c2a = A.state_attributes.get("card2") or {}
        c2b = {}
        for k, v in c2a.items():
            stripped = v
            for c in concepts:
                stripped = stripped.replace(c, "【剥离】")
            c2b[k] = stripped

        class _Mini:
            pass

        B = _Mini()
        B.state_attributes = {"name": f"{na}（不含{concepts[0]}）", "card2": c2b}
        B.content = A.content

        results = {}
        for label, ent in (("版本A(完整)", A), ("版本B(剥离)", B)):
            results[label] = [{"move": mv["name"],
                               "status": self._probe(ent, mv["desc"])["status"]}
                              for mv in self.OPERATION_MOVES]

        def off(rr):
            return sum(1 for x in rr if x["status"] in ("边界暴露", "崩溃"))

        a_off, b_off = off(results["版本A(完整)"]), off(results["版本B(剥离)"])
        if a_off == 0 and b_off == 0:
            conclusion = "两版本一致稳定——条件论是更高效的表达方式而非必要条件（智能论已隐含条件意识）"
        elif b_off > a_off:
            conclusion = "版本B(剥离)更不稳定——条件论是智能论的结构性补全，不可或缺"
        else:
            conclusion = "版本A更不稳定（异常）——需复核剥离是否失真"
        return {"entry": na, "剥离概念": concepts,
                "测试": results,
                "偏移统计": {"版本A": a_off, "版本B": b_off},
                "结论": conclusion,
                "note": "内部同源性检验（P34）：条件论是装饰还是必要结构——添加功能还是揭示已有结构"}

