    def _moves(self, entry):
        """条目条件检验招式：MOVES 表优先，缺省以不可约起点自动生成一条检验。"""
        name = entry.state_attributes.get("name")
        if name in self.MOVES:
            return self.MOVES[name]
        c2 = entry.state_attributes.get("card2") or {}
        seed = c2.get("irreducible_start") or entry.content
        return [{"name": f"{name}条件检验", "desc": seed[:40]}]

    def _probe(self, defender, move_desc):
        """单招测试（P24 四类结果）· 带命中文本细节（可用于反馈）。"""
        c2 = defender.state_attributes.get("card2") or {}
        roles = {"existence_preset": "核心：存在预设",
                 "irreducible_start": "核心：不可约起点",
                 "observation_method": "结构：观测方式",
                 "time_causality": "结构：时间因果",
                 "condition_boundary": "结构：条件边界"}
        hits = []
        for key, role in roles.items():
            text = c2.get(key, "")
            if text:
                s = self._overlap(move_desc, text)
                if s > 0.12:
                    hits.append({"element": role, "score": round(s, 2),
                                 "text": text[:80]})
        if not hits:
            if self._overlap(move_desc, defender.content) <= 0.05:
                return {"status": "对抗无效", "hits": [],
                        "note": f"两条件空间不重叠：招式「{move_desc[:20]}」与目标识别卡无概念交集，测试无效果（反馈：可扩大招式覆盖或调整表述）"}
            return {"status": "稳定", "hits": [],
                    "note": f"测试通过：招式「{move_desc[:20]}」未触及目标条件维度（反馈：确认该条件下边界稳固）"}
        if any("核心" in h["element"] for h in hits):
            return {"status": "崩溃", "hits": hits,
                    "note": "内部不自洽（核心预设/不可约起点受扰）"}
        return {"status": "边界暴露", "hits": hits,
                "note": "出现偏移，偏移位置可标记"}

