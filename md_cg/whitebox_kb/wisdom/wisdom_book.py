def _nid(seed):
    """确定性节点 id：种子串 sha256 前 12 位 + 毫秒时戳后缀。"""
    h = hashlib.sha256(seed.encode("utf-8")).hexdigest()[:12]
    return f"wis_{h}_{int(time.time() * 1000)}"


