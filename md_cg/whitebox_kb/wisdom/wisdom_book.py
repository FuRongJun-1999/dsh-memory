class ConditionDex:
    """条件论查询门面（Dex）：知识层为工作区——卡片种子导入、条件分离、
    卡片四要素分析与路由验证的主入口对象。"""

    def __init__(self, db_path=None, fresh=False):
        """Dex 构造：复用或新建灵枢引擎，知识层为工作区。"""
        self.db_path = db_path or DEFAULT_DB
        d = os.path.dirname(self.db_path)
        if d and self.db_path != ":memory:":
            os.makedirs(d, exist_ok=True)
        if fresh and self.db_path != ":memory:" and os.path.exists(self.db_path):
            os.remove(self.db_path)
        self.engine = SpacetimeMemoryEngine(db_path=self.db_path,
                                            identity="智慧之书",
                                            role=Role.PRIMARY)
        self.store = self.engine.store
        self.engine.store.set_meta("project", "智慧之书")
        self.engine.store.set_meta("base", "存在论/条件论/智能论/物理学/信息论/概率论/博弈论")
        self._by_name = {}

    def close(self):
        """关闭底层灵枢引擎与存储连接。"""
        self.engine.close()

    # ---- 写入 ----

    def add_entry(self, name, domain, claim, cs, level=2, status="pending",
                  response=None, tags=None, card2=None, tier=None, tests=None):
        """录入知识条目：name/domain/claim + 条件空间 cs → 感知节点写入知识层（打 domain:/level:/status: 标签）。"""
        node = self.engine.add_perception(
            claim, modality="text", condition_space=cs,
            importance=min(0.95, 0.6 + 0.1 * level),
            tags=list(dict.fromkeys(
                [f"domain:{domain}", f"level:L{level}", f"status:{status}"] + (tags or []))))
        node.confidence = min(0.95, 0.4 + 0.12 * level)
        node.state_attributes = {"name": name, "domain": domain, "level": level,
                                 "status": status, "response": response or {},
                                 "kind": "knowledge"}
        if tier:
            node.state_attributes["tier"] = tier
            node.tags.append(f"tier:{tier}")
        if card2:
            node.state_attributes["card2"] = card2  # 识别卡 2.0（8+1 字段）
        if tests:
            node.state_attributes["tests"] = tests  # 关联测试（可观测判据集）
        self.store.add_node(node)  # upsert：附加图谱元数据
        self._by_name[name] = node.id
        return node.id

    def add_relation(self, a_name, b_name, kind, note="", confidence=0.8):
        """在两个命名条目间建边：kind 映射 EdgeType（默认 SIMILAR），note 写入存在约束，confidence 为边置信度。"""
        et = getattr(EdgeType, kind.upper(), EdgeType.SIMILAR)
        cond = _default_cs()
        cond.existence_constraint = note or cond.existence_constraint
        edge = self.engine.add_edge(self._by_name[a_name], self._by_name[b_name],
                                    relation_type=et, confidence=confidence,
                                    condition_space=cond, source_evidence="inferred")
        self.engine.verify_edge(edge.id, confidence)  # 基底关系已验证
        return edge.id

    # ---- 基底装载（幂等：已播种则跳过） ----

    def seed_base(self):
        """导入知识论种子卡（幂等：已存在 domain:存在论 标签则跳过）。"""
        existing = self.store.query_nodes(layer=MemoryLayer.KNOWLEDGE, limit=300)
