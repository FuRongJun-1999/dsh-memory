    def dex_respond(self, condition, limit=10, translator=None):
        """条件响应（全链路检索）。

        translator：可选知识翻译模块（semantic_translate），传入后启用
        编码解码检索——查询先编码成语义指纹（日常俗语→规范知识词），
        三路评分：
          1) 语义指纹命中：规范词直击 trigger/name/content
          2) 学科路由：规范词→学科域→卡的 domain（教育层级加权，E1/E2 优先）
          3) 字符重叠兜底：原 _overlap 能力
        不传 translator 时保持原行为（纯字符重叠）。
        """
        fp = {}
        q_sc = {}
        _sp = None
        if translator is not None:
            fp = translator.encode(condition)
            # 语义坐标：查询投影一次（灵枢 L1/L2 轴，零依赖）
            try:
                from aeis_core.semantic import SemanticSpaceProvider as _SSP
                _sp = _SSP()
                q_sc = _sp.to_semantic_coordinates(condition)
            except Exception:
                _sp = None
        edu_w_map = {"E1": 2.5, "E2": 2.0, "E3": 1.5, "E4": 1.0, "E5": 0.8}
        # v1.16 学段先验：问题含「定律/公式/原理/定理」等系统概念时，
        # E1 小学（现象层）不优先——「光的反射定律」该命中初中物理而非小学科学
        if any(w in condition for w in ("定律", "公式", "原理", "定理", "规律")):
            edu_w_map["E1"] = 0.8
        hits = []
        # v1.16 性能优化：主库 11045 节点，全量遍历慢（1000 条测试 5.28s/条）。
        # SQL 预过滤「有名字的卡」（学科卡/元层卡/元学科卡 state_attributes 含 name；
        # 工作记录/感知记忆大多无 name）→ 只遍历 ~110 张卡，快 ~100 倍。
        from aeis_core import STNode as _STNode
        try:
            _rows = self.store.conn.execute(
                "SELECT * FROM nodes WHERE layer='knowledge' "
                "AND state_attributes LIKE '%\"name\"%' "
                "AND tags NOT LIKE '%knowledge_point%'").fetchall()
            _nodes = [_STNode.from_row(tuple(r)) for r in _rows]
        except Exception:
            _nodes = self.store.query_nodes(layer=MemoryLayer.KNOWLEDGE, limit=50000)
        for n in _nodes:
            sa = n.state_attributes
            if not sa.get("name"):
                continue
            resp = sa.get("response") or {}
            # v1.16 修复：学科卡（迁移自 *_knowledge.json）无 response.trigger →
            # 快速层全 miss（只靠神经层）。无 trigger 时用 content 前 200 字符兜底。
            trig = str(resp.get("trigger", "") or "") or (n.content or "")[:200]
            content = n.content or ""
            domain = sa.get("domain", "") or ""

            if translator is not None:
                # ---- 翻译检索：三路评分（fp 可为空，学科词直配仍生效） ----
                score = 0.0
                matched = []
                edu_w = edu_w_map.get(sa.get("edu_level"), 1.0)
                # 1) 语义指纹命中
                for term, w in fp.items():
                    if term and (term in trig or term in sa.get("name", "")):
                        score += w * 2.0 * edu_w
                        if term not in matched:
                            matched.append(term)
                    elif term and term in content:
                        score += w * 1.0 * edu_w
                        if term not in matched:
                            matched.append(term)
                # 2) 学科路由（教育层级加权）
                for term, w in fp.items():
                    dom = getattr(translator, 'DOMAIN_ROUTE', {}).get(term)
                    if dom and (dom in domain or any(dom in t for t in (n.tags or []))):
                        score += w * 1.2 * edu_w
                        if dom not in matched:
                            matched.append(dom)
                # 2.5) 学科词直配：trigger「如：」后的学科关键词与查询双向包含
                #      （不依赖翻译表——「TCP三次握手」直接命中 TCP 词条）
                kp_start = trig.find("（如：")
                if kp_start >= 0:
                    kp_list = [k.strip() for k in
                               trig[kp_start + 3:trig.rfind("）")].split("、")
                               if k.strip()]
                    for kp in kp_list:
                        if len(kp) >= 2 and (kp in condition
                                             or (len(kp) >= 4 and condition in kp)):
                            score += 1.5 * edu_w
                            if kp not in matched:
                                matched.append(kp)
                    # 2.6) 单字学科词兜底：查询为单字（熵/场/波）时，
                    #      trigger 中以该字开头的学科词条（熵增定律/电磁场）也算命中
                    if len(condition.strip()) == 1:
                        ch = condition.strip()
                        for kp in kp_list:
                            if len(kp) >= 2 and kp.startswith(ch):
                                score += 1.2 * edu_w
                                if kp not in matched:
                                    matched.append(kp)
                # 2.7) 英文缩写兜底（v1.16：KKT/SVM/API 不在翻译表，
                #      查卡名与 content 开头——「KKT条件」命中约束优化卡）
                if not matched:
                    import re as _re2
                    for _m in _re2.finditer(r"[A-Za-z]{2,}", condition):
                        _ew = _m.group(0).lower()
                        if _ew in (sa.get("name", "") or "").lower() \
                                or _ew in (content or "")[:200].lower():
                            score += 1.5 * edu_w
                            if _ew not in matched:
                                matched.append(_ew)
                            break
                # 2.8) 中文术语直配（v1.16：测度论/普朗克——学科术语不在
                #      翻译表，问题关键词窗口 in 卡名/卡内容——
                #      「测度论」in 卡名、「普朗克」in 知识点内容）
                # v1.17 修复（2026-08-19 白箱边界测试）：通用疑问词过滤——
                # 「什么是质数？」fp 为空时「什么」2 字窗口命中所有卡，
                # 小学语文靠 E1 权重乱赢（质数→小学语文→质量错配）。
                # 疑问词/虚词不进窗口匹配，术语直配只认实义窗口。
                if not matched:
                    _chars = [ch for ch in condition if "\u4e00" <= ch <= "\u9fff"]
                    _cname = sa.get("name", "") or ""
                    _cwin = _cname + (content or "")[:600]
                    # 过滤通用疑问词（不参与窗口匹配）
                    _STOP_CHARS = ("什么", "怎么", "为什么", "多少", "哪些", "哪个",
                                   "如何", "是不是", "是什么", "怎么办", "好不好",
                                   "对不对", "会不会", "为什么", "为啥", "咋")
                    _hit = False
                    for _L in (4, 3, 2):
                        for _i in range(len(_chars) - _L + 1):
                            _w = "".join(_chars[_i:_i + _L])
                            if any(s in _w for s in _STOP_CHARS):
                                continue
                            if _w in _cwin:
                                score += {4: 2.0, 3: 1.5, 2: 1.0}[_L] * edu_w
                                if _w not in matched:
                                    matched.append(_w)
                                _hit = True
                                break
                        if _hit:
                            break
                # 3) 二元组命中兜底（灵枢式查询侧召回，替代单字符重叠）
                overlap = self._bigram_hit(condition, trig)
                if overlap > 0:
                    score += overlap * 0.3
                    if "字面" not in matched:
                        matched.append("字面")
                # 4) 语义坐标余弦（灵枢语义空间：部首义类+协议符号投影）
                #    仅翻译表有命中时启用——fp 为空说明查询是单字学科词
                #    （熵/场）或生僻表达，部首投影噪声大，交给神经层
                if _sp is not None and q_sc and fp:
                    n_sc = getattr(n, 'semantic_coordinates', {}) or {}
                    cos = _sp.similarity_coordinates(q_sc, n_sc)
                    if cos > 0.05:
                        score += cos * 1.5 * edu_w
                        if "语义" not in matched:
                            matched.append("语义")
                if score <= 0:
                    continue
                self.store.increment_access(n.id)  # P29：使用频次
                daily = None
                for term in fp:
                    d = getattr(translator, 'REVERSE_DAILY', {}).get(term)
                    if d:
                        daily = d
                        break
                hits.append({"name": sa.get("name"), "score": round(score, 2),
                             "action": resp.get("action", ""),
                             "level": sa.get("level"), "status": sa.get("status"),
                             "domain": domain, "edu_level": sa.get("edu_level"),
                             "matched": matched, "daily": daily})
            else:
                # ---- 原行为：字符重叠 ----
                score = self._overlap(condition, trig)
                if score > 0:
                    self.store.increment_access(n.id)  # P29：使用频次
                    hits.append({"name": sa.get("name"), "score": round(score, 2),
                                 "action": resp.get("action", ""),
                                 "level": sa.get("level"), "status": sa.get("status")})
        hits.sort(key=lambda x: -x["score"])
        return hits[:limit]

