//! issue #659 F26-25（2026-10-28）：拉丁语系**重音折叠表**（零第三方依赖）。
//!
//! 背景：`normalize_en` 原先把非 ASCII、非中文的字符一律变空格 ⇒ `café` → `caf`，
//! 而 Python 侧 `fold_accents`（NFKC → NFD → 剥组合记号 → NFC）给 `cafe`，两侧互不可命中。
//! `rust/Cargo.toml` 明写「零第三方依赖」（与 md_cg 的 D-005 约束一致，无需联网取 crate），
//! 故不能用 `unicode-normalization`，只能内置表。
//!
//! 表的**生成口径**（与 Python 精确对齐）：枚举 Unicode，取「NFD 分解结果去掉
//! U+0300–U+036F / U+1AB0–U+1AFF / U+1DC0–U+1DFF 三区间的 Mn 后仍为**单字符**，
//! 且与原字符不同」的字符。据此：
//!   · `é`(U+00E9) → `e`、`ñ` → `n`、`Ü` → `U`；
//!   · `ß`(U+00DF) **不在表里**——它没有规范分解，Python 也不变；
//!   · 日文浊点 `が`(U+304C) **不在表里**——其组合记号 U+3099 不在三区间内，
//!     这正是 Python 侧 #659 F26-27 修过的「不得折叠浊音对立」。
//!
//! 覆盖范围（2026-10-28 修正后）：按「Python `fold_accents` 能折的全部」生成，
//! 覆盖拉丁四区 + 希腊/希腊扩展 + 西里尔 + 兼容区（共 0 条）。
//! 初版只收拉丁四区，结果「Rust 不折、Python 折希腊」构成新分叉——
//! 这正是本模块头一开始警告过的「扩表前先加跨实现守卫样例」的反面教材。
//! 现由 `scripts/test_rust_fold_parity.py` 逐条核对，任何一侧改动都会红。
//! 本仓检索主战场是中英混排，那三类重音几乎不出现；若将来需要，照同一口径扩表即可，
//! 但**扩表前先加跨实现一致性守卫的样例**，否则会造出「Rust 折、Python 不折」的新分叉。

